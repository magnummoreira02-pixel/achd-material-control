// Template element schema
export function createDefaultElement(tipo, overrides = {}) {
  const base = {
    id: Date.now().toString() + Math.random().toString(36).substr(2),
    tipo,
    x: 0,
    y: 0,
    // default dimensions will be relative to label size
    fonteMm: 3,
    negrito: false,
    alinhamento: "esq",
    rotacao: "horizontal",
    caixaBorda: false,
    larguraFixa: false,
    alturaFixa: false,
    ...overrides
  };
  return base;
}